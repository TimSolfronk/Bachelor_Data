with open(args.file_name, newline="", encoding="utf-8") as f:
    csvData= list(csv.reader(f, delimiter=','))

# replace the body entry according to the tracer ID
for entry in csvData:
    if entry[0] in change_map[args.scenario].keys():
        entry[3] = " " + change_map[args.scenario][entry[0]]

# output the data
